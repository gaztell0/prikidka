export const DEFAULT_LANG = 'ru';

export function normalizeLang(value) {
  return value === 'en' ? 'en' : DEFAULT_LANG;
}

export function translate(lang, key, vars = {}) {
  const dictionary = MESSAGES[lang] ?? MESSAGES[DEFAULT_LANG];
  const template = dictionary[key] ?? MESSAGES[DEFAULT_LANG][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name) => (
    Object.hasOwn(vars, name) ? String(vars[name]) : placeholder
  ));
}

export function localeFor(lang) {
  return lang === 'en' ? 'en-US' : 'ru-RU';
}

export function decimalSeparatorFor(lang) {
  return lang === 'en' ? '.' : ',';
}

